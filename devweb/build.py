#!/usr/bin/env python3
"""Assemble the DevWeb script folders from _src/.

DevWeb runs each script folder on its own, so every main.js is self-contained:
    <script>/main.js = header + _src/common.js [+ _src/fixtures.js] + _src/<script>.js
plus a scenario.yml. Edit the files in _src/, then run:

    python build.py            # write the folders
    python build.py --check    # fail if a folder is out of date
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SCRIPTS = ['init', 'vars', 'lists', 'names', 'mail', 'sms', 'totp', 'webhook', 'lock', 'qr', 'perf', 'multi']
WITH_FIXTURES = {'init', 'mail', 'multi'}
SCENARIO = """# DevWeb scenario (OpenText Performance Engineering for Developers / load mode).
# All times are in seconds. In LoadRunner Professional, Enterprise or Cloud, set
# the same in the scenario instead.
vusers: {vusers}
pacing:
  type: delay
  mode: fixed
  value: {pacing}
rampUp: {rampup}
duration: {duration}
tearDown: 0
"""


def read(*p):
    with open(os.path.join(HERE, *p), encoding='utf-8') as f:
        return f.read()


def build(name):
    parts = [f"// Test Helper API - DevWeb regression suite: '{name}' script.\n"
             f"// GENERATED by devweb/build.py from devweb/_src/ - edit the sources, not this file.\n\n"
             f"const SCRIPT = '{name}';\n\n",
             read('_src', 'common.js')]
    if name in WITH_FIXTURES:
        parts.append('\n' + read('_src', 'fixtures.js'))
    parts.append('\n' + read('_src', f'{name}.js'))
    main = ''.join(parts)
    if name == 'init':
        scen = SCENARIO.format(vusers=1, pacing=1, rampup=0, duration=300)
    else:
        scen = SCENARIO.format(vusers=3, pacing=1, rampup=3, duration=120)
    return {os.path.join(HERE, name, 'main.js'): main, os.path.join(HERE, name, 'scenario.yml'): scen}


def main():
    check = '--check' in sys.argv
    stale = []
    for name in SCRIPTS:
        for path, content in build(name).items():
            cur = open(path, encoding='utf-8').read() if os.path.exists(path) else None
            if cur != content:
                stale.append(os.path.relpath(path, HERE))
                if not check:
                    os.makedirs(os.path.dirname(path), exist_ok=True)
                    with open(path, 'w', encoding='utf-8', newline='\n') as f:
                        f.write(content)
    if check and stale:
        raise SystemExit('stale: ' + ', '.join(stale) + ' - run python devweb/build.py')
    print('up to date' if not stale else 'built: ' + ', '.join(stale))


if __name__ == '__main__':
    main()
