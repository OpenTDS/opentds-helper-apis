"""Builds the small documents the DevWeb scripts upload (embedded as base64).

    python make_fixtures.py      (needs reportlab, pikepdf and qpdf)
"""
import base64, json, subprocess, io
from reportlab.lib.pagesizes import A4
from reportlab.pdfgen import canvas
import pikepdf, zipfile

def invoice(path, total):
    c = canvas.Canvas(path, pagesize=A4)
    c.setTitle('Regression Invoice'); c.setAuthor('Test Helper API'); c.setSubject('DevWeb regression fixture')
    y = 780
    c.setFont('Helvetica-Bold', 14); c.drawString(60, y, 'TEST HELPER API REGRESSION INVOICE'); y -= 40
    c.setFont('Helvetica', 11)
    for label, value in (('Invoice number', 'TH-REG-0001'), ('Order number', 'ORD-778899'),
                         ('Customer', 'Regression Customer'), ('Total excluding GST', '$112.23'),
                         ('Total including GST', total)):
        c.drawString(60, y, label); c.drawString(300, y, value); y -= 22
    c.drawString(60, y - 10, 'Marker PAGE1-OK')
    c.showPage()
    c.setFont('Helvetica', 11); c.drawString(60, 780, 'Second page marker PAGE2-OK'); c.save()
    with pikepdf.open(path, allow_overwriting_input=True) as p:
        p.docinfo['/InvoiceNumber'] = 'TH-REG-0001'
        p.save(path)

invoice('invoice.pdf', '$123.45')
invoice('invoice-v2.pdf', '$132.45')
subprocess.run(['qpdf', '--encrypt', 'Reg-2468', 'Owner-1357', '256', '--', 'invoice.pdf', 'invoice-locked.pdf'], check=True)
CT = ('<?xml version="1.0" encoding="UTF-8"?><Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">'
      '<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>'
      '<Default Extension="xml" ContentType="application/xml"/>'
      '<Override PartName="/word/document.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/></Types>')
RELS = ('<?xml version="1.0" encoding="UTF-8"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
        '<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="word/document.xml"/></Relationships>')
DOC = ('<?xml version="1.0" encoding="UTF-8"?><w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"><w:body>'
       + ''.join('<w:p><w:r><w:t>%s</w:t></w:r></w:p>' % p for p in ('Regression note DOCX-OK', 'Reference TH-REG-0001'))
       + '</w:body></w:document>')
with zipfile.ZipFile('note.docx', 'w', zipfile.ZIP_DEFLATED) as z:
    z.writestr('[Content_Types].xml', CT); z.writestr('_rels/.rels', RELS); z.writestr('word/document.xml', DOC)
out = {n: base64.b64encode(open(f, 'rb').read()).decode() for n, f in
       (('invoicePdf', 'invoice.pdf'), ('invoiceV2Pdf', 'invoice-v2.pdf'), ('invoiceLockedPdf', 'invoice-locked.pdf'), ('noteDocx', 'note.docx'))}
with open('../fixtures.js', 'w') as f:
    f.write('// Generated by _src/fixtures/make_fixtures.py - small test documents, base64.\n')
    f.write('// invoice*.pdf: 2 pages, "Invoice number  TH-REG-0001", "Total including GST  $123.45"\n')
    f.write('// (v2: $132.45), metadata InvoiceNumber=TH-REG-0001. invoiceLockedPdf: AES-256, open\n')
    f.write('// password Reg-2468, owner password Owner-1357. noteDocx: "Regression note DOCX-OK".\n')
    f.write('const FIXTURES = ' + json.dumps(out, indent=1) + ';\n')
print({k: len(v) for k, v in out.items()})
